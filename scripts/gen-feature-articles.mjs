// One-off generator: turns the 12 CMS feature posts into CODE articles so they
// no longer depend on the CMS (no admin login, no push, no HTML sanitiser that
// strips <figure>/style). Reads the saved CMS JSON + the admin/app draft steps
// and app screenshots from feature-docs.mjs, injects them, and emits
// src/content/articles/features.ts.
//
//   node scripts/gen-feature-articles.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { FEATURE_DOCS } from './feature-docs.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = '/private/tmp/claude-501/-Users-alexandergerhard-Bygg-exp-dev-ByggExp-NextJs/ce9978be-2d6a-4418-9ef0-92666f8272b7/scratchpad/features';
const OUT = path.join(ROOT, 'src/content/articles/features.ts');

function buildBlock(doc) {
  const ol = (steps) => `<ol>\n${steps.map((s) => `<li>${s}</li>`).join('\n')}\n</ol>`;
  const parts = [];
  if (doc.webbadmin?.length) parts.push(`<h2>Så gör du i webbadmin</h2>\n${ol(doc.webbadmin)}`);
  if (doc.appen?.length) parts.push(`<h2>Så gör du i appen</h2>\n${ol(doc.appen)}`);
  if (doc.ecosystem) parts.push(`<p class="eco-note"><strong>Allt hänger ihop:</strong> ${doc.ecosystem}</p>`);
  if (doc.images?.length) {
    const imgs = doc.images
      .map((im) => `<img src="${im.src}" alt="${im.alt}" loading="lazy">`)
      .join('');
    const cap = doc.imagesCaption ? `<figcaption>${doc.imagesCaption}</figcaption>` : '';
    parts.push(`<figure class="app-shots">${imgs}${cap}</figure>`);
  }
  return parts.join('\n');
}

function inject(html, block) {
  const stegRe = /<h2>\s*Så kommer du igång[\s\S]*?(?=<h2>)/;
  if (stegRe.test(html)) return html.replace(stegRe, `${block}\n`);
  const faqRe = /<h2>\s*Vanliga frågor/;
  if (faqRe.test(html)) return html.replace(faqRe, `${block}\n<h2>Vanliga frågor`);
  return `${html}\n${block}`;
}

const objects = Object.keys(FEATURE_DOCS).map((slug) => {
  const j = JSON.parse(fs.readFileSync(path.join(SRC, `${slug}.json`), 'utf8'));
  const contentHtml = inject(j.contentHtml || '', buildBlock(FEATURE_DOCS[slug]));
  const post = {
    _id: `code-${slug}`,
    title: j.title,
    slug,
    locale: 'sv',
    excerpt: j.excerpt || '',
    tag: j.tag || '',
    coverImageUrl: j.coverImageUrl || '',
    contentHtml,
    seoTitle: j.seoTitle || j.title,
    seoDescription: j.seoDescription || j.excerpt || '',
    seoImageUrl: j.seoImageUrl || '',
    canonicalUrl: '',
    noIndex: false,
    isPublished: true,
    publishedAt: j.publishedAt || j.createdAt || null,
    createdAt: j.createdAt || j.publishedAt || '',
    updatedAt: j.updatedAt || j.createdAt || '',
  };
  return post;
});

const body =
  `// Feature pages ("Funktioner"), moved from the CMS into code so they can be\n` +
  `// edited freely (layout, screenshots) and deployed via git — no admin login or\n` +
  `// HTML sanitiser. Generated by scripts/gen-feature-articles.mjs. The [slug] page\n` +
  `// serves code before CMS, so these win over the (now stale) CMS copies.\n` +
  `import type { BlogPost } from '../../types/blog';\n\n` +
  `export const FEATURE_ARTICLES: BlogPost[] = ${JSON.stringify(objects, null, 2)};\n`;

fs.writeFileSync(OUT, body);
console.log(`wrote ${OUT} with ${objects.length} feature articles`);
