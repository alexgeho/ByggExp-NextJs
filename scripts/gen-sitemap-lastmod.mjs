#!/usr/bin/env node
// Builds src/content/sitemap-lastmod.generated.ts (gitignored) before `next build`
// so every <url> in /sitemap.xml gets a real <lastmod>: the last git commit that
// changed the page's own source, not the build date.
//
// How a date is found (git blame per line, committer time):
//   - Slug pages (/sv/funktioner/<slug>, /nb/funksjoner/<slug>, code blog
//     articles): only the lines of that page's object in src/content/** plus the
//     top-level constants it references (e.g. the article's *_HTML body), plus
//     slug-keyed entries in other content files (quick answers, heroes).
//   - Static routes (/sv, /sv/verktyg/x, /sv/priser, …): the route file in
//     src/pages/[lang]/ and its direct relative imports, minus site chrome
//     (Header/Footer, lib, types, styles). Locale-keyed files (src/locales/*,
//     content maps keyed sv/en/nb…) count only the lines of that language block.
//
// Needs full git history (CI: actions/checkout fetch-depth: 0). Without git the
// file is written empty and the sitemap simply omits lastmod as before.

import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const OUT = path.join(ROOT, 'src/content/sitemap-lastmod.generated.ts');
const PAGES_DIR = path.join(ROOT, 'src/pages/[lang]');
const CONTENT_DIR = path.join(ROOT, 'src/content');
const LANGS = ['sv', 'en', 'ru', 'nb', 'pl', 'uk', 'fi', 'et', 'lt', 'lv'];

const CHROME = [
  /^src\/components\/(Header|Footer)\//,
  /^src\/locales\/(header|footer|languages|index|translations)\.ts$/,
  /^src\/lib\//,
  /^src\/types\//,
  /\.s?css$/,
  /sitemap-lastmod\.generated\.ts$/,
];

function write(data) {
  const body = `// GENERATED by scripts/gen-sitemap-lastmod.mjs — do not edit, not committed.\n` +
    `export type LastmodMap = Record<string, string>;\n` +
    `export const ROUTE_LASTMOD: Record<string, LastmodMap> = ${JSON.stringify(data.routes, null, 0)};\n` +
    `export const PAGE_LASTMOD: LastmodMap = ${JSON.stringify(data.pages, null, 0)};\n` +
    `export const BLOG_LASTMOD: LastmodMap = ${JSON.stringify(data.blog, null, 0)};\n`;
  fs.writeFileSync(OUT, body);
}

function git(args) {
  return execFileSync('git', args, { cwd: ROOT, encoding: 'utf8', maxBuffer: 256 * 1024 * 1024 });
}

try {
  git(['rev-parse', '--git-dir']);
  if (git(['rev-parse', '--is-shallow-repository']).trim() === 'true') {
    console.warn('[sitemap-lastmod] shallow clone — dates may be too new; use fetch-depth: 0');
  }
} catch {
  console.warn('[sitemap-lastmod] no git — writing empty lastmod map');
  write({ routes: {}, pages: {}, blog: {} });
  process.exit(0);
}

const rel = (abs) => path.relative(ROOT, abs).split(path.sep).join('/');

// ---- per-line commit times ------------------------------------------------
const blameCache = new Map();
function lineTimes(file) {
  if (blameCache.has(file)) return blameCache.get(file);
  let times = [];
  try {
    const out = git(['blame', '-w', '--line-porcelain', '--', file]);
    let cur = 0;
    for (const line of out.split('\n')) {
      if (line.startsWith('committer-time ')) cur = Number(line.slice(15));
      else if (line.startsWith('\t')) times.push(cur);
    }
  } catch {
    times = [];
  }
  blameCache.set(file, times);
  return times;
}
function maxTime(file, ranges) {
  const times = lineTimes(file);
  let m = 0;
  for (const [a, b] of ranges) for (let i = a; i <= b && i < times.length; i++) if (times[i] > m) m = times[i];
  return m;
}
const wholeFile = (file) => maxTime(file, [[0, Number.MAX_SAFE_INTEGER]]);
const iso = (t) => new Date(t * 1000).toISOString();

const readLines = (file) => fs.readFileSync(path.join(ROOT, file), 'utf8').split('\n');
const indentOf = (s) => s.match(/^\s*/)[0].length;

// ---- top-level declaration segments ---------------------------------------
const TOP = /^(export\s+)?(const|let|function|type|interface|enum)\s+([A-Za-z0-9_$]+)/;
function segments(lines) {
  const segs = [];
  lines.forEach((l, i) => {
    const m = l.match(TOP);
    if (m) {
      if (segs.length) segs[segs.length - 1].end = i - 1;
      segs.push({ name: m[3], start: i, end: lines.length - 1 });
    }
  });
  return segs;
}

// ---- locale-keyed blocks (  sv: {…}, nb: '…') ------------------------------
const LANG_LINE = new RegExp(`^  (${LANGS.join('|')})\\s*:`);
function langRanges(lines) {
  const res = { shared: [] };
  let cur = null;
  let start = 0;
  const close = (end) => {
    if (end < start) return;
    (cur ? (res[cur] ||= []) : res.shared).push([start, end]);
  };
  lines.forEach((l, i) => {
    const m = l.match(LANG_LINE);
    if (m) { close(i - 1); cur = m[1]; start = i; }
    else if (cur && l.length && indentOf(l) === 0) { close(i - 1); cur = null; start = i; }
  });
  close(lines.length - 1);
  return res;
}
function fileTimeForLang(file, lang) {
  if (!/^src\/(locales|content)\//.test(file)) return wholeFile(file);
  const lines = readLines(file);
  const r = langRanges(lines);
  const keyed = LANGS.filter((l) => r[l]).length;
  if (keyed < 2) return wholeFile(file);
  return maxTime(file, [...r.shared, ...(r[lang] || [])]);
}

// ---- slug blocks in src/content/** -----------------------------------------
function listFiles(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((d) => {
    const p = path.join(dir, d.name);
    return d.isDirectory() ? listFiles(p) : /\.(ts|tsx)$/.test(d.name) ? [p] : [];
  });
}

const SLUG_LINE = /\bslug:\s*['"`]([a-z0-9-]+)['"`]/;
const KEY_LINE = /^  ['"]([a-z0-9-]+)['"]\s*:/;
const pages = {};
const blog = {};
const keyed = {}; // slug-keyed maps (quick answers, heroes): slug → time
const bump = (map, key, t) => { if (t > (map[key] || 0)) map[key] = t; };

for (const abs of listFiles(CONTENT_DIR)) {
  const file = rel(abs);
  if (file.endsWith('.generated.ts')) continue;
  const lines = readLines(file);
  const segs = segments(lines);
  const segByName = new Map(segs.map((s) => [s.name, s]));
  const segAt = (i) => segs.find((s) => s.start <= i && i <= s.end);
  const slugLines = [];
  lines.forEach((l, i) => { const m = l.match(SLUG_LINE); if (m) slugLines.push([i, m[1]]); });
  const slugsPerSeg = new Map();
  slugLines.forEach(([i]) => { const s = segAt(i); if (s) slugsPerSeg.set(s, (slugsPerSeg.get(s) || 0) + 1); });

  const isArticle = file.startsWith('src/content/articles/');
  const isPage = /^src\/content\/(funktion-pages(-[abc])?|funksjon-pages-nb)\.ts$/.test(file);
  if (isArticle || isPage) {
    for (const [i, slug] of slugLines) {
      const seg = segAt(i);
      let range;
      if (seg && slugsPerSeg.get(seg) === 1 && seg.start <= i) {
        range = [seg.start, seg.end];
      } else {
        // object inside an array: from the enclosing "{" to its "}" (by indent)
        const ind = indentOf(lines[i]);
        let a = i;
        while (a > 0 && !(indentOf(lines[a]) < ind && /\{\s*$/.test(lines[a]))) a--;
        if (lines[i].trimStart().startsWith('{') || /^\s*\{/.test(lines[i])) a = i;
        const oi = indentOf(lines[a]);
        let b = i;
        while (b < lines.length - 1 && !(b > i && indentOf(lines[b]) <= oi && /^\s*\}/.test(lines[b]))) b++;
        range = [a, b];
      }
      const ranges = [range];
      // top-level constants referenced inside the block (article *_HTML bodies,
      // shared helpers); skip list constants that hold several pages.
      const text = lines.slice(range[0], range[1] + 1).join('\n');
      for (const ident of new Set(text.match(/\b[A-Za-z_$][A-Za-z0-9_$]*\b/g) || [])) {
        const s = segByName.get(ident);
        if (s && s !== seg && !(slugsPerSeg.get(s) > 1)) ranges.push([s.start, s.end]);
      }
      const block = lines.slice(range[0], range[1] + 1).join('\n');
      const lm = block.match(/\blocale:\s*['"]([a-z]{2})['"]/);
      const locale = lm ? lm[1] : file.includes('-nb') ? 'nb' : 'sv';
      bump(isArticle ? blog : pages, `${locale}:${slug}`, maxTime(file, ranges));
    }
  } else {
    // slug-keyed maps: '  'some-slug': { … }' until the next key / top level line
    const keys = [];
    lines.forEach((l, i) => { const m = l.match(KEY_LINE); if (m) keys.push([i, m[1]]); });
    keys.forEach(([i, slug], k) => {
      let b = k + 1 < keys.length ? keys[k + 1][0] - 1 : lines.length - 1;
      for (let j = i + 1; j <= b; j++) if (lines[j].length && indentOf(lines[j]) === 0) { b = j - 1; break; }
      bump(keyed, slug, maxTime(file, [[i, b]]));
    });
  }
}
for (const key of Object.keys(blog)) {
  const slug = key.slice(3);
  if (keyed[slug]) bump(blog, key, keyed[slug]);
}

// ---- static routes ----------------------------------------------------------
const IMPORT = /^\s*import\s+(?:type\s+)?[^'"]*?from\s+['"](\.[^'"]+)['"]|^\s*import\s+['"](\.[^'"]+)['"]/;
function resolveImport(fromAbs, spec) {
  const base = path.resolve(path.dirname(fromAbs), spec);
  for (const c of [base, `${base}.ts`, `${base}.tsx`, path.join(base, 'index.ts'), path.join(base, 'index.tsx')]) {
    if (fs.existsSync(c) && fs.statSync(c).isFile()) return c;
  }
  return null;
}
function directImports(abs) {
  const src = fs.readFileSync(abs, 'utf8');
  // collapse multi-line import lists so the regex sees one line per import
  const flat = src.replace(/import\s+(type\s+)?\{[^}]*\}/g, (m) => m.replace(/\s+/g, ' '));
  const out = [];
  for (const l of flat.split('\n')) {
    const m = l.match(IMPORT);
    if (!m) continue;
    const r = resolveImport(abs, m[1] || m[2]);
    if (r) out.push(r);
  }
  return out;
}

const routes = {};
for (const abs of listFiles(PAGES_DIR)) {
  const r = rel(abs);
  if (r.includes('[slug]')) continue;
  const route = path.relative(PAGES_DIR, abs).split(path.sep).join('/').replace(/\.tsx?$/, '').replace(/(^|\/)index$/, '');
  const deps = [r, ...directImports(abs).map(rel).filter((d) => !CHROME.some((re) => re.test(d)))];
  routes[route] = {};
  for (const lang of LANGS) {
    let t = 0;
    for (const d of deps) t = Math.max(t, fileTimeForLang(d, lang));
    if (t) routes[route][lang] = iso(t);
  }
}

const toIso = (m) => Object.fromEntries(Object.entries(m).filter(([, t]) => t).map(([k, t]) => [k, iso(t)]));
write({ routes, pages: toIso(pages), blog: toIso(blog) });
console.log(`[sitemap-lastmod] ${Object.keys(routes).length} routes, ${Object.keys(pages).length} feature pages, ${Object.keys(blog).length} articles`);
